#!/usr/bin/env python3
"""Generate the pg_sta upgrade script from the base extension script.

PostgreSQL applies an upgrade with

    ALTER EXTENSION pg_sta UPDATE TO '<new version>';

and looks for <extension>--<old version>--<new version>.sql in the
extension directory.  That file must contain the *new* definitions of the
functions whose behaviour changed; everything else is already in the
database and must not be touched.

This script extracts exactly those function definitions from the base
script so that the two files cannot drift apart.  It is run by
"make upgrade-script" and its output is committed.

Usage:  python3 scripts/gen_upgrade.py [old_version] [new_version]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lint_sql import tokenize  # noqa: E402

# The functions that changed between the two versions.  A function that is
# new in the new version is listed here as well: CREATE OR REPLACE creates
# it when it does not exist yet.  The order matters: a function is created
# after the functions it uses.
CHANGED = [
    "sta._explain_safe",
    "sta._format_sql",
    "sta._sql_relname",
    "sta._sql_first_word_alias",
    "sta._sql_index_ddl",
    "sta._sql_values_are_normalized",
    "sta._sql_relid",
    "sta._sql_relation_columns",
    "sta._sql_outer_relations",
    "sta._sql_column_type",
    "sta.plan_advice",
    "sta.index_advice",
    "sta.statement_advice",
    "sta._raw_statement",
    "sta.record",
    "sta._workload_targets",
    "sta._workload_delta",
    "sta.stats_advice",
    "sta.rewrite_advice",
    "sta.rewrite_statement",
    "sta.recommendations",
    "sta.action_plan",
    "sta.action_script",
    "sta.advice_catalog",
]

# The tables that are new in the new version.  The upgrade creates them
# with IF NOT EXISTS, so the script can be applied to a database that
# already has them.
TABLES = [
    "sta.workload_statement",
]

HEADER = """\
-- pg_sta {old} -> {new} upgrade script
--
-- Generated by scripts/gen_upgrade.py from sql/pg_sta--{new}.sql.
-- Do not edit by hand: run "make upgrade-script" instead.
--
-- Apply it with:
--
--     ALTER EXTENSION pg_sta UPDATE TO '{new}';
--
\\echo Use "ALTER EXTENSION pg_sta UPDATE TO '{new}'" to load this file. \\quit
"""


def statement_end(src, start):
    """Return the offset just past the ';' that ends the statement at start."""
    toks = tokenize(src[start:])
    depth = 0
    for kind, val, s, e in toks:
        if kind != "op":
            continue
        if val == "(":
            depth += 1
        elif val == ")":
            depth -= 1
        elif val == ";" and depth == 0:
            return start + e
    return None


def extract_function(src, name):
    m = re.search(r"(?m)^CREATE (?:OR REPLACE )?FUNCTION\s+%s\s*\("
                  % re.escape(name), src)
    if not m:
        raise SystemExit("gen_upgrade: function %s not found" % name)
    end = statement_end(src, m.start())
    if end is None:
        raise SystemExit("gen_upgrade: cannot find the end of %s" % name)
    body = src[m.start():end]
    # the upgrade script must not create a function that already exists
    return body.replace("CREATE FUNCTION ", "CREATE OR REPLACE FUNCTION ", 1)


def extract_comment(src, name):
    for m in re.finditer(r"(?m)^COMMENT ON FUNCTION\s+([A-Za-z_][\w.]*)\s*\(", src):
        if m.group(1) != name:
            continue
        end = statement_end(src, m.start())
        if end:
            return src[m.start():end]
    return None


def extract_table(src, name):
    """The CREATE TABLE of a table and the indexes that belong to it."""
    m = re.search(r"(?m)^CREATE TABLE\s+%s\s*\(" % re.escape(name), src)
    if not m:
        raise SystemExit("gen_upgrade: table %s not found" % name)
    end = statement_end(src, m.start())
    if end is None:
        raise SystemExit("gen_upgrade: cannot find the end of %s" % name)
    body = src[m.start():end]

    # An upgrade must not fail because the table is already there.
    body = body.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)

    parts = [body]
    for m2 in re.finditer(r"(?m)^CREATE INDEX\s+([A-Za-z_][\w]*)\s+ON\s+%s\s*\("
                          % re.escape(name), src):
        e = statement_end(src, m2.start())
        if e:
            idx = src[m2.start():e]
            idx = idx.replace("CREATE INDEX ", "CREATE INDEX IF NOT EXISTS ", 1)
            parts.append(idx)
    return "\n".join(parts)


def main():
    old = sys.argv[1] if len(sys.argv) > 1 else "0.1.0"
    new = sys.argv[2] if len(sys.argv) > 2 else "0.1.1"
    here = os.path.dirname(os.path.abspath(__file__))
    base_path = os.path.join(here, "..", "sql", "pg_sta--%s.sql" % new)
    src = open(base_path).read()

    parts = [HEADER.format(old=old, new=new)]
    for name in TABLES:
        parts.append("")
        parts.append(extract_table(src, name))
    for name in CHANGED:
        parts.append("")
        parts.append(extract_function(src, name))
        c = extract_comment(src, name)
        if c:
            parts.append(c)

    out_path = os.path.join(here, "..", "sql",
                            "pg_sta--%s--%s.sql" % (old, new))
    with open(out_path, "w") as fh:
        fh.write("\n".join(parts).rstrip() + "\n")
    print("wrote %s (%d functions)" % (os.path.relpath(out_path, here),
                                       len(CHANGED)))


if __name__ == "__main__":
    main()
